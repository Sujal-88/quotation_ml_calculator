"""### 4. Build the ML Model 1: Future Business Forecast
We will aggregate the order data into weekly revenue time-series, build lagged features, and train a regression forecast model.
"""

import sqlite3
import pandas as pd
import numpy as np
from statsmodels.tsa.holtwinters import ExponentialSmoothing
from sklearn.metrics import mean_absolute_error, r2_score
import matplotlib.pyplot as plt

# 1. Load and aggregate data
conn = sqlite3.connect('/content/DB/my_database.db')
df = pd.read_sql_query("SELECT date_created, total_amount FROM orders;", conn)
conn.close()

df['date_created'] = pd.to_datetime(df['date_created']).dt.tz_localize(None)
df_weekly = df.set_index('date_created').resample('W')['total_amount'].sum().reset_index()

# Handle the extreme outlier at the very end
q_limit = df_weekly['total_amount'].quantile(0.95)
df_weekly['total_amount_capped'] = df_weekly['total_amount'].clip(upper=q_limit)

# Split into Train and Test (80/20 time-based split)
split_idx = int(len(df_weekly) * 0.8)
train_series = df_weekly.iloc[:split_idx].set_index('date_created')['total_amount_capped']
test_series = df_weekly.iloc[split_idx:].set_index('date_created')['total_amount_capped']

# Fit Holt-Winters Exponential Smoothing (additive trend, no seasonality due to short span)
model = ExponentialSmoothing(train_series, trend='add', seasonal=None, initialization_method='estimated')
fitted_model = model.fit()

# Forecast for the test period
y_pred = fitted_model.forecast(len(test_series))

# Evaluate
mae = mean_absolute_error(test_series, y_pred)
r2 = r2_score(test_series, y_pred)

print(f"--- Robust Exponential Smoothing Forecast Evaluation ---")
print(f"Mean Absolute Error on weekly revenue forecast: ${mae:.2f}")
print(f"R2 Score (Capped Revenue Baseline): {r2:.4f}")

# Generate future 4-week forecast beyond the dataset
future_forecast = fitted_model.forecast(len(test_series) + 4).iloc[-4:]
print("\n--- Future 4-Week Business Forecast ---")
for date, val in future_forecast.items():
    print(f"Week ending {date.strftime('%Y-%m-%d')}: Projected Revenue: ${val:.2f}")

# Plot actual, test prediction, and future forecast
plt.figure(figsize=(12, 5))
plt.plot(train_series.index, train_series, label='Train Revenue (Capped)', color='blue')
plt.plot(test_series.index, test_series, label='Test Actual Revenue (Capped)', color='green', marker='o')
plt.plot(test_series.index, y_pred, label='Test Predicted Revenue', color='orange', linestyle='--', marker='x')
plt.title("Robust Business Revenue Forecast (Holt-Winters)")
plt.xlabel("Date")
plt.ylabel("Weekly Total Amount ($)")
plt.legend()
plt.grid(True)
plt.show()

