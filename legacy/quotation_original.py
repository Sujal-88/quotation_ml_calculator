"""### 5. Build the ML Model 2: Quotation Calculation Model
We will parse the details of each order to extract specifications such as sheet counts, GSM, paper supply flags, and build a model to estimate final pricing.
"""

import json
from sklearn.ensemble import GradientBoostingRegressor
from sklearn.model_selection import train_test_split

conn = sqlite3.connect('/content/DB/my_database.db')
df_quotes = pd.read_sql_query("SELECT total_amount, details FROM orders WHERE details IS NOT NULL;", conn)
conn.close()

# Parse details
rows = []
for idx, row in df_quotes.iterrows():
    try:
        details = json.loads(row['details'])

        # Safely extract specs
        binding = details.get('bindingDetails', 'No Binding')
        lamination_list = details.get('lamination', [])
        has_lamination = 1 if len(lamination_list) > 0 else 0

        # Parse paper entries specs
        paper_entries = details.get('paperEntries', [])
        gsm = 0
        sheets_qty = 0
        if paper_entries:
            # Try to get GSM as a float
            try:
                gsm = float(paper_entries[0].get('gSM', 0))
            except:
                pass

            # Extract sheet quantity (e.g. "3200 Sheets" -> 3200)
            paper_qty_str = paper_entries[0].get('paperQuantity', '0')
            try:
                sheets_qty = float(''.join(filter(str.isdigit, paper_qty_str)))
            except:
                pass

        rows.append({
            'total_amount': row['total_amount'],
            'binding': binding,
            'has_lamination': has_lamination,
            'gsm': gsm,
            'sheets_qty': sheets_qty
        })
    except:
        continue

df_quote_features = pd.DataFrame(rows)

# Encode categorical values
df_quote_features = pd.get_dummies(df_quote_features, columns=['binding'], drop_first=True)

# Prepare target and features
X_q = df_quote_features.drop('total_amount', axis=1)
y_q = df_quote_features['total_amount']

X_q_train, X_q_test, y_q_train, y_q_test = train_test_split(X_q, y_q, test_size=0.2, random_state=42)

# Train gradient boosted trees to estimate quotation costs
quote_model = GradientBoostingRegressor(n_estimators=150, random_state=42)
quote_model.fit(X_q_train, y_q_train)

# Evaluate
y_q_pred = quote_model.predict(X_q_test)
mae_q = mean_absolute_error(y_q_test, y_q_pred)
r2_q = r2_score(y_q_test, y_q_pred)

print(f"--- Quotation Estimation Model Evaluation ---")
print(f"Mean Absolute Error on Quotations: ${mae_q:.2f}")
print(f"R2 Score: {r2_q:.4f}")

def predict_quote(sheets_qty, gsm, has_lamination, binding_type):
    # Reconstruct the feature structure expected by our model
    # Recall the training features: has_lamination, gsm, sheets_qty, and one-hot-encoded binding flags
    feature_cols = list(X_q.columns)
    input_data = {col: 0 for col in feature_cols}

    # Populate base features
    input_data['sheets_qty'] = sheets_qty
    input_data['gsm'] = gsm
    input_data['has_lamination'] = int(has_lamination)

    # Populate the encoded categorical binding key if it exists in features
    binding_col = f'binding_{binding_type}'
    if binding_col in input_data:
        input_data[binding_col] = 1
    elif binding_type != 'No Binding':
        # Print warning if we haven't seen this specific binding type during training
        pass

    # Build DataFrame matching training structure
    input_df = pd.DataFrame([input_data])[feature_cols]

    # Predict price
    predicted_price = quote_model.predict(input_df)[0]
    return max(0, predicted_price) # Price cannot be negative

